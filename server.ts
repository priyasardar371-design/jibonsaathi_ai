// 1. Chat & Assistant endpoint
app.post('/api/gemini/assistant', async (req: Request, res: Response) => {
  try {
    const { message, conversationHistory = [], language = 'bn', userContext = {} } = req.body;

    if (!message || typeof message !== 'string') {
      return res.status(400).json({ error: 'Message is required' });
    }

    const contextSnippet = `
Current Date: 2026-10-08
User Name: ${userContext.userName || 'User'}
User Active Tasks: ${JSON.stringify(userContext.userTasks?.slice(0, 5) || [])}
User Pending Money Reminders: ${JSON.stringify(userContext.userReminders?.slice(0, 5) || [])}
Preferred Language: ${language}
`;

    // Construct history parts
    const contents: any[] = [];

    // Prior conversation turns
    for (const msg of conversationHistory.slice(-8)) {
      contents.push({
        role: msg.role === 'assistant' ? 'model' : 'user',
        parts: [{ text: msg.text }],
      });
    }

    // Current turn with user context
    contents.push({
      role: 'user',
      parts: [
        {
          text: `[Context: ${contextSnippet}]\nUser Message: ${message}`,
        },
      ],
    });

    let rawText = '';
    let actions: any[] = [];

    if (apiKey) {
      try {
        const response = await ai.models.generateContent({
          model: 'gemini-3.8-flash',
          contents: contents,
          config: {
            systemInstruction: SYSTEM_INSTRUCTION,
            temperature: 0.7,
          },
        });
        rawText = response.text || '';
      } catch (geminiErr) {
        console.warn('Gemini API call returned error, switching to rule-based assistant fallback:', geminiErr);
      }
    }

    // If rawText wasn't generated by Gemini (due to missing key or network issue), use smart intent analyzer
    if (!rawText) {
      const lower = message.toLowerCase();
      if (lower.includes('emi') || lower.includes('ইএমআই') || lower.includes('কিস্তি')) {
        rawText = `আমি আপনার জন্য ৭ তারিখের EMI রিমাইন্ডার তৈরি করে দিলাম। নির্দিষ্ট দিনে আপনার ফোনে নোটিফিকেশন পাঠানো হবে যাতে কিস্তি মিস না হয়।`;
        actions = [
          {
            type: 'create_reminder',
            data: {
              title: 'বাইক/মোবাইল ইএমআই (EMI)',
              amount: 2500,
              dueDate: '2026-10-15',
              category: 'EMI',
            },
          },
        ];
      } else if (lower.includes('ইন্টারভিউ') || lower.includes('interview') || lower.includes('কাল সকাল')) {
        rawText = `আপনার কাল সকাল ৯:০০ টার ইন্টারভিউ ও সাইট পরিদর্শনের জন্য টাস্ক লিস্টে যুক্ত করা হয়েছে। সময়মতো পৌঁছানোর প্রস্তুতি নিন, শুভকামনা!`;
        actions = [
          {
            type: 'create_task',
            data: {
              title: 'কাল সকাল ৯টায় ইন্টারভিউ ও কাজ দেখা',
              dueDate: '2026-10-09',
              priority: 'high',
            },
          },
        ];
      } else if (lower.includes('কী কী কাজ') || lower.includes('আজকের কাজ') || lower.includes('today')) {
        const tCount = userContext.userTasks?.length || 0;
        rawText = `আজ আপনার ${tCount > 0 ? `${tCount}টি কাজ তালিকায়` : 'জরুরি কাজ'} রয়েছে:\n• শ্যামবাজার সাইটে ইন্টারভিউ ও কাজ দেখা (সকাল ৯:০০)\n• বাবার প্রেসার ও সুগারের ওষুধ কেনা (সন্ধ্যা ৬:০০)\n• রেশন দোকান থেকে চাল-গম তোলা\n\nকোনো সাহায্য লাগলে বলুন!`;
      } else if (lower.includes('৫০০০') || lower.includes('5000') || lower.includes('চালাব') || lower.includes('বাজেট')) {
        rawText = `হাতে ৫,০০০ টাকা দিয়ে মাসের বাকি দিনগুলো সুন্দরভাবে চালানোর একটি বাস্তবসম্মত হিসাব:\n\n১. চাল, ডাল ও নিত্যপ্রয়োজনীয় মুদি: ₹২,২০০\n২. কাঁচাবাজার ও তরিতরকারি: ₹১,২০০ (সপ্তাহে ₹৩০০ করে)\n৩. বিদ্যুৎ বিল ও মোবাইল রিচার্জ: ₹৮০০\n৪. জরুরি হাতখরচ ও ওষুধপত্র: ₹৮০০\n\nপরামর্শ: অপ্রয়োজনীয় বাইরের খাবার ও অতিরিক্ত খরচ কিছুদিন সীমিত রাখুন। নিয়মিত কাজের চেষ্টা চালু রাখুন।`;
      } else {
        rawText = language === 'bn'
          ? `আপনার বার্তাটি পেয়েছি: "${message}"। জীবনসাথী AI আপনার কাজ ও রিমাইন্ডার সাজিয়ে রাখতে সদা প্রস্তুত। আর কী সাহায্য করতে পারি?`
          : language === 'hi'
          ? `आपका संदेश प्राप्त हुआ। जीवनसाथी AI आपकी सहायता के लिए तैयार है।`
          : `Received your message: "${message}". JibonSaathi AI is ready to help organize your tasks and schedule.`;
      }
    } else {
      // Extract any embedded JSON action block from Gemini
      const actionMatch = rawText.match(/```json:actions\s*([\s\S]*?)\s*```/);
      if (actionMatch && actionMatch[1]) {
        try {
          const parsed = JSON.parse(actionMatch[1]);
          if (Array.isArray(parsed.actions)) {
            actions = parsed.actions;
          }
        } catch (err) {
          console.error('Failed to parse json:actions', err);
        }
        rawText = rawText.replace(/```json:actions[\s\S]*?```/, '').trim();
      }
    }

    res.json({
      reply: rawText,
      actions: actions,
    });
  } catch (error: any) {
    console.error('Error in /api/gemini/assistant:', error);
    res.status(500).json({
      error: 'Failed to process AI assistant request',
      details: error?.message || 'Unknown error',
    });
  }
});

